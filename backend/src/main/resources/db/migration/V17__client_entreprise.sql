-- Clients de type entreprise (raison sociale dans nom, identifiants facultatifs) et factures A4.
alter table client
    add column type               varchar(12)  not null default 'PARTICULIER',
    add column ice                varchar(15),
    add column identifiant_fiscal varchar(20),
    add column rc                 varchar(30),
    add column contact            varchar(120),
    add column adresse            varchar(300),
    add column email              varchar(120),
    add constraint ck_client_type check (type in ('PARTICULIER', 'ENTREPRISE')),
    add constraint ck_client_ice check (ice is null or ice ~ '^[0-9]{15}$');

-- Facture d'une vente avec client, numérotée sans trou par année (FA-2026-00042) à sa première
-- impression ; l'identité du client y est figée, une réimpression ressort la même facture.
create table compteur_facture (
    annee   integer primary key,
    dernier integer not null
);

create table facture (
    id                        bigint generated by default as identity primary key,
    numero                    varchar(20)  not null,
    vente_id                  bigint       not null references vente (id),
    client_type               varchar(12)  not null,
    client_nom                varchar(120) not null,
    client_ice                varchar(15),
    client_identifiant_fiscal varchar(20),
    client_rc                 varchar(30),
    client_contact            varchar(120),
    client_adresse            varchar(300),
    emise_par                 bigint       not null references utilisateur (id),
    emise_le                  timestamptz  not null,
    constraint uk_facture_numero unique (numero),
    constraint uk_facture_vente unique (vente_id)
);
