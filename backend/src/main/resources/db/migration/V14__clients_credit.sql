-- Annuaire des clients et vente à crédit. La dette d'un client ne change que par des mises à jour
-- conditionnelles atomiques ; chaque changement est inscrit à son relevé (mouvement_client, ajout seul).

create table client (
    id        bigint generated by default as identity primary key,
    nom       varchar(120)   not null,
    telephone varchar(30),
    note      varchar(300),
    actif     boolean        not null default true,
    dette     numeric(12, 2) not null default 0,
    cree_le   timestamptz    not null,
    constraint ck_client_dette check (dette >= 0)
);
create index ix_client_nom on client (lower(nom));

-- Relevé d'un client. montant signé : + la dette augmente (vente à crédit, annulation d'un
-- remboursement), − elle baisse (remboursement). especes / tpe : répartition d'un remboursement.
create table mouvement_client (
    id                bigint generated by default as identity primary key,
    client_id         bigint         not null references client (id),
    type              varchar(30)    not null,
    montant           numeric(12, 2) not null,
    especes           numeric(12, 2),
    tpe               numeric(12, 2),
    vente_id          bigint references vente (id),
    -- Remboursement annulé par cette écriture (type ANNULATION_REMBOURSEMENT).
    remboursement_id  bigint references mouvement_client (id),
    annule            boolean        not null default false,
    -- Qui a encaissé (ou vendu) ; session ouverte à ce moment : l'argent est entré dans son tiroir.
    utilisateur_id    bigint         not null references utilisateur (id),
    session_caisse_id bigint references session_caisse (id),
    -- Remboursement encaissé par l'admin : il entre directement dans la caisse principale.
    caisse_principale boolean        not null default false,
    motif             varchar(300),
    dette_apres       numeric(12, 2) not null,
    cle_idempotence   uuid,
    cree_le           timestamptz    not null,
    constraint ck_mouvement_client_type
        check (type in ('VENTE_CREDIT', 'REMBOURSEMENT', 'ANNULATION_REMBOURSEMENT')),
    constraint ck_mouvement_client_montant check (montant <> 0),
    constraint uk_mouvement_client_cle unique (cle_idempotence)
);
create index ix_mouvement_client_client on mouvement_client (client_id, cree_le desc, id desc);
create index ix_mouvement_client_session on mouvement_client (session_caisse_id)
    where type = 'REMBOURSEMENT';

-- Client de la vente (facultatif, obligatoire à crédit), figé sur le ticket avec sa dette après la vente.
alter table vente
    add column client_id          bigint references client (id),
    add column client_nom         varchar(120),
    add column dette_client_apres numeric(12, 2);
create index ix_vente_client on vente (client_id);

alter table paiement drop constraint ck_paiement_mode;
alter table paiement add constraint ck_paiement_mode check (mode in ('ESPECES', 'CARTE', 'CREDIT'));
