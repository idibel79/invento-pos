-- Trésorerie : caisse principale (admin) et compte de chaque caissier, versements entre eux et
-- journal des opérations. Comptes, versements et journal ne sont lus et écrits qu'en SQL
-- (mises à jour conditionnelles atomiques des soldes).

create table compte_tresorerie (
    id             bigint generated by default as identity primary key,
    type           varchar(12)    not null,
    utilisateur_id bigint references utilisateur (id),
    solde          numeric(12, 2) not null default 0,
    constraint ck_compte_type check (type in ('PRINCIPALE', 'CAISSIER')),
    constraint ck_compte_titulaire check ((type = 'PRINCIPALE') = (utilisateur_id is null)),
    -- La caisse principale n'est jamais négative. Le solde stocké d'un caissier peut l'être pendant une
    -- session ouverte : ses ventes n'y sont reportées qu'à la clôture (solde affiché = stocké + ventes).
    constraint ck_compte_principale_positive check (type = 'CAISSIER' or solde >= 0),
    constraint uk_compte_utilisateur unique (utilisateur_id)
);
create unique index uk_compte_principale on compte_tresorerie (type) where type = 'PRINCIPALE';

insert into compte_tresorerie (type, solde) values ('PRINCIPALE', 0);
insert into compte_tresorerie (type, utilisateur_id, solde) select 'CAISSIER', id, 0 from utilisateur;

-- Versement entre un caissier et la caisse principale (jamais entre deux caissiers) : débité chez
-- l'émetteur à l'envoi, crédité chez le récepteur quand il confirme l'avoir reçu.
create table versement (
    id                   bigint generated by default as identity primary key,
    emetteur_id          bigint         not null references compte_tresorerie (id),
    recepteur_id         bigint         not null references compte_tresorerie (id),
    montant              numeric(12, 2) not null,
    statut               varchar(12)    not null,
    motif                varchar(300),
    -- Session ouverte de l'émetteur à l'envoi / du récepteur à la réception (argent sorti du tiroir ou
    -- entré dedans) : sert au calcul de l'attendu à la clôture.
    session_emission_id  bigint references session_caisse (id),
    session_reception_id bigint references session_caisse (id),
    cloture              boolean        not null default false,
    auto_valide          boolean        not null default false,
    cle_idempotence      uuid,
    cree_par             bigint         not null references utilisateur (id),
    cree_le              timestamptz    not null,
    traite_par           bigint references utilisateur (id),
    traite_le            timestamptz,
    constraint ck_versement_montant check (montant > 0),
    constraint ck_versement_statut check (statut in ('EN_TRANSIT', 'VALIDE', 'REFUSE', 'ANNULE')),
    constraint ck_versement_comptes check (emetteur_id <> recepteur_id),
    constraint uk_versement_cle unique (cle_idempotence)
);
create index ix_versement_emetteur on versement (emetteur_id);
create index ix_versement_recepteur on versement (recepteur_id);
create index ix_versement_en_transit on versement (recepteur_id) where statut = 'EN_TRANSIT';
create index ix_versement_session_emission on versement (session_emission_id);
create index ix_versement_session_reception on versement (session_reception_id);

-- Journal de la caisse principale, en ajout seul : une ligne par mouvement de solde, avec les soldes
-- de la caisse principale et du caissier concerné juste après.
create table operation_tresorerie (
    id                     bigint generated by default as identity primary key,
    type                   varchar(30)    not null,
    compte_id              bigint         not null references compte_tresorerie (id),
    montant                numeric(12, 2) not null,
    caissier_id            bigint references utilisateur (id),
    caisse_id              bigint references caisse (id),
    session_caisse_id      bigint references session_caisse (id),
    versement_id           bigint references versement (id),
    ecart_session          numeric(12, 2),
    motif                  varchar(300),
    solde_principale_apres numeric(12, 2) not null,
    solde_caissier_apres   numeric(12, 2),
    auteur_id              bigint         not null references utilisateur (id),
    cle_idempotence        uuid,
    cree_le                timestamptz    not null,
    constraint uk_operation_tresorerie_cle unique (cle_idempotence)
);
create index ix_operation_tresorerie_date on operation_tresorerie (cree_le, id);
create index ix_operation_tresorerie_caissier on operation_tresorerie (caissier_id);
create index ix_operation_tresorerie_versement on operation_tresorerie (versement_id);

-- Clôture d'office (caisse désactivée) : la session attend que l'admin compte le tiroir.
alter table session_caisse add column comptage_en_attente boolean not null default false;
